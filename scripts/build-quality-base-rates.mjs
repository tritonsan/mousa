// Builds plugin/server/culture/quality-base-rates.mjs: for each look, mood and meaning tag Qloo returns on measured
// works, how often an audience's works carry it, averaged over a reference set of audiences. The engine ranks an
// audience's shared qualities by how much more often its own works carry a tag than this base rate, so a tag Qloo puts
// on almost every film, show and record (Intimate, Atmospheric, Minimalist) no longer leads every audience.
//
//   node scripts/build-quality-base-rates.mjs [--write] <folder>...
//
// The folders are searched for saved taste profiles (.mousa/taste/profile.json); each audience (its seeds, place and
// segments) counts once, however many runs measured it. The profiles hold Qloo's answers and stay on this machine; the
// module keeps only tag names and the shares computed from them. Without --write it prints what it would keep.
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { normalizeTasteName, isQualityDomain } from '../plugin/server/culture/taste.mjs';

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const target = path.join(repo, 'plugin', 'server', 'culture', 'quality-base-rates.mjs');
// A tag rarer than this across the reference audiences is treated as this rare: two works carrying it are then a
// strong but bounded signal.
const FLOOR = 0.004;
const SKIP = new Set(['node_modules', 'cache', 'captures', 'fonts', 'kiro', 'generated', '.git', 'history']);

async function profilesUnder(dir, found = []) {
  for (const entry of await fs.readdir(dir, { withFileTypes: true }).catch(() => [])) {
    if (SKIP.has(entry.name)) continue;
    const file = path.join(dir, entry.name);
    if (entry.isDirectory()) await profilesUnder(file, found);
    else if (entry.name === 'profile.json' && path.basename(path.dirname(file)) === 'taste') found.push(file);
  }
  return found;
}

const args = process.argv.slice(2);
const folders = args.filter(arg => !arg.startsWith('--'));
if (!folders.length) throw new Error('Name one or more folders holding saved taste profiles.');
const files = (await Promise.all(folders.map(folder => profilesUnder(path.resolve(folder))))).flat();
const audiences = new Map();
for (const file of files) {
  const profile = await fs.readFile(file, 'utf8').then(JSON.parse, () => null);
  const works = (profile?.entities || []).filter(entity => !isQualityDomain(entity.domain) && Object.values(entity.facets || {}).some(values => values?.length));
  if (works.length < 10) continue;
  const key = [...(profile.seeds || []).map(seed => normalizeTasteName(seed.name)).sort(), normalizeTasteName(profile.location), ...(profile.audiences || [])].join(';');
  if (!audiences.has(key)) audiences.set(key, works);
}
// The share of an audience's tagged works that carry each tag, then its mean over the audiences (absent counts as 0).
const sums = new Map();
for (const works of audiences.values()) {
  const counts = new Map();
  for (const work of works) for (const key of new Set(Object.values(work.facets).flat().map(normalizeTasteName).filter(Boolean))) counts.set(key, (counts.get(key) || 0) + 1);
  for (const [key, count] of counts) sums.set(key, (sums.get(key) || 0) + count / works.length);
}
const rates = [...sums.entries()].map(([key, sum]) => [key, sum / audiences.size]).filter(([, rate]) => rate >= FLOOR).sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]));
console.log(`${files.length} profiles, ${audiences.size} audiences, ${sums.size} tags; ${rates.length} at or above the floor of ${FLOOR}.`);
console.log(`Most common: ${rates.slice(0, 12).map(([key, rate]) => `${key} ${(100 * rate).toFixed(1)}%`).join(', ')}.`);
if (args.includes('--write')) {
  const day = new Date().toISOString().slice(0, 10);
  const body = rates.map(([key, rate]) => `  ${JSON.stringify(key)}: ${Number(rate.toFixed(4))},`).join('\n');
  await fs.writeFile(target, `// Generated by scripts/build-quality-base-rates.mjs on ${day}; do not edit by hand. For each look, mood and meaning tag
// Qloo returns on measured works, the mean share of an audience's tagged works that carry it, over ${audiences.size} audiences measured
// in Moûsa sessions (${files.length} saved profiles, each audience counted once). Tags rarer than the floor are left out and read as
// the floor. Only tag names and these shares are kept; the profiles they come from stay off the repository.
export const QUALITY_BASE_RATES_CORPUS = Object.freeze({ audiences: ${audiences.size}, profiles: ${files.length}, builtAt: '${day}', floor: ${FLOOR} });

export const QUALITY_BASE_RATES = Object.freeze({
${body}
});
`);
  console.log(`Wrote ${path.relative(repo, target)}.`);
}
